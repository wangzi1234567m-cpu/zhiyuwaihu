 const id='00000000-0000-0000-0000-000000000001';
 await page.addInitScript(sid=>localStorage.setItem('zhiyu.session',sid),id);
 await page.route('**/api/v1/applications',r=>r.fulfill({json:[{application_id:id,label:'申请单 1',company_hint:'演示商家1'}]}));
 await page.route('**/api/v1/capabilities',r=>r.fulfill({json:{voice:false,realtime_webrtc:false,model:'fake'}}));
 await page.route('**/events?*',r=>r.fulfill({contentType:'text/event-stream',body:': ready\n\n'}));
 await page.route('**/api/v1/sessions/'+id,r=>r.fulfill({json:{session_id:id,application_id:id,state:'QA',state_revision:3,last_event_seq:10,mode:'text',ended:false,busy:false,messages:[{message_id:'m1',role:'assistant',text:'请问您是演示商家1吗？',status:'completed'},{message_id:'m2',role:'user',text:'我是演示商家1',status:'completed'}]}}));
